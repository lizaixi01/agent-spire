export function icon(name: string, cls = "", size = 24): string {
  const d = (glyphs[name] ?? glyphs.spark)
    .flatMap((row, y) =>
      [...row].flatMap((v, x) => (v === "1" ? [`M${x} ${y}h1v1h-1z`] : [])),
    )
    .join("");
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 8 8" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true"><path d="${d}"/></svg>`;
}
