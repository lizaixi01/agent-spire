type Choice = [text: string, reason: string];
export interface BeginnerQuestion extends TrialQuestion {
  id: string;
  level: "beginner";
  intro: string;
  scene: string;
  hint: string;
  optionReasons: [string, string, string];
}
let sequence = 0;
function question(lessonId: string, key: string, title: string, scene: string, prompt: string,
  right: Choice, wrongA: Choice, wrongB: Choice, hint: string): BeginnerQuestion {
  const lesson = LESSON_BY_ID[lessonId], correct = sequence++ % 3;
  const choices: Choice[] = [right, wrongA, wrongB];
  const ordered = [0,1,2].map(i => choices[(i - correct + 3) % 3]);
  return { id: `intro-${lessonId}-${key}`, lessonId, chapter: lesson.chapter, section: lesson.section, page: lesson.page,
    title, level: "beginner", intro: FOUNDATIONS[lessonId], scene, question: prompt, code: "",
    options: ordered.map(c => c[0]), correct, optionReasons: ordered.map(c => c[1]) as BeginnerQuestion["optionReasons"],
    explanation: right[1], hint };
}

